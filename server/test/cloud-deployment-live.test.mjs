const enabled = process.env.YAP_DEPLOYMENT_LIVE_TEST === '1' && process.env.YAP_BASE_URL && process.env.YAP_WORKER_TOKEN;
test('live Vercel: guest isolation, clarification, signed upload, finalize, preview and download', { skip: !enabled }, async () => {
  const base = process.env.YAP_BASE_URL.replace(/\/$/, '');
  const guest = 'guest_' + randomBytes(32).toString('hex');
  const other = 'guest_' + randomBytes(32).toString('hex');
  const id = randomUUID();
  const request = async (path, token, method = 'GET', body, lease) => {
    const response = await fetch(base + path, {
      method, headers: {
        ...(token ? { Authorization: 'Bearer ' + token } : {}),
        ...(body ? { 'Content-Type': 'application/json' } : {}),
        ...(lease ? { 'X-YAP-Lease': lease } : {}),
      }, ...(body ? { body: JSON.stringify(body) } : {}),
      signal: AbortSignal.timeout(120000),
    });
    const json = response.status === 204 ? null : await response.json();
    return { status: response.status, json };
  };
  const worker = process.env.YAP_WORKER_TOKEN;
  const submit = { id, prompt: 'Cloud transport verification fixture; not a Muse-generated app', responseMode: 'chat' };
  assert.equal((await request('/api/capabilities')).status, 200);
  assert.equal((await request('/api/build', guest, 'POST', submit)).status, 202);
  assert.equal((await request('/api/build', guest, 'POST', submit)).status, 200);
  assert.equal((await request('/api/build/' + id, other)).status, 404);
  assert.equal((await request('/api/build/claim', guest, 'POST', { claimRequestId: randomUUID() })).status, 401);
  let claimed = await request('/api/build/claim', worker, 'POST', { claimRequestId: randomUUID() });
  assert.equal(claimed.status, 200, 'claim must succeed');
  assert.equal(claimed.json.id, id, 'do not mutate another queued job');
  let lease = claimed.json.lease;
  const question = await request(`/api/build/${id}/question`, worker, 'PUT', { operationId: randomUUID(), question: 'Is this a transport test only?' }, lease);
  assert.equal(question.status, 200);
  assert.equal(question.json.status, 'awaiting_answer');
  const answer = { questionId: question.json.clarification.id, answer: 'Yes, transport verification only.' };
  assert.equal((await request(`/api/build/${id}/answer`, other, 'POST', answer)).status, 404);
  assert.equal((await request(`/api/build/${id}/answer`, guest, 'POST', answer)).status, 200);
  claimed = await request('/api/build/claim', worker, 'POST', { claimRequestId: randomUUID() });
  assert.equal(claimed.status, 200);
  assert.equal(claimed.json.id, id);
  assert.equal(claimed.json.clarifications[0].answer, answer.answer);
  lease = claimed.json.lease;
  const apk = await readFile(new URL('./fixtures/test-app.apk', import.meta.url));
  const sha256 = createHash('sha256').update(apk).digest('hex');
  const prepare = await request(`/api/build/${id}/artifacts/prepare`, worker, 'POST', { operationId: randomUUID(), kind: 'apk', size: apk.length, sha256 }, lease);
  assert.equal(prepare.status, 200);
  const upload = await fetch(prepare.json.uploadUrl, { method: 'PUT', headers: { 'Content-Type': 'application/vnd.android.package-archive' }, body: apk, signal: AbortSignal.timeout(120000) });
  assert.ok(upload.ok, `Storage upload HTTP ${upload.status}`);
  const meta = await request(`/api/build/${id}/metadata`, worker, 'PUT', { operationId: randomUUID(), appName: 'YAP Transport Fixture' }, lease);
  assert.equal(meta.status, 200);
  const finalized = await request(`/api/build/${id}/result`, worker, 'PUT', {
    operationId: randomUUID(), artifactId: prepare.json.artifactId,
    verification: { note: 'Signed fixture for transport verification, not generated by Muse in this test.' },
  }, lease);
  assert.equal(finalized.status, 200, 'finalize must verify Storage bytes and publish');
  assert.equal(finalized.json.status, 'ready');
  assert.equal(finalized.json.sha256, sha256);
  assert.equal(finalized.json.size, apk.length);
  assert.equal((await request(`/api/build/${id}/download`, other)).status, 404);
  const download = await request(`/api/build/${id}/download`, guest);
  assert.equal(download.status, 200);
  const bytes = Buffer.from(await (await fetch(download.json.url, { signal: AbortSignal.timeout(120000) })).arrayBuffer());
  assert.equal(createHash('sha256').update(bytes).digest('hex'), sha256);
  const preview = await request(`/api/build/${id}/preview`, guest);
  assert.equal(preview.status, 200);
  assert.match(preview.json.html, /preview-marker-7f3a9/);
  console.log(JSON.stringify({ evidence: 'cloud-transport-fixture', jobId: id, size: apk.length, sha256, status: 'ready', clarificationVerified: true, guestIsolationVerified: true, previewVerified: true, downloadVerified: true }));
});

test('live Supabase TUS transfers exactly 32 MiB without Vercel request-body upload', { skip: !enabled || process.env.YAP_LARGE_TRANSFER_TEST !== '1' }, async () => {
  const base = process.env.YAP_BASE_URL.replace(/\/$/, '');
  const id = randomUUID();
  const guest = 'guest_' + randomBytes(32).toString('hex');
  const worker = process.env.YAP_WORKER_TOKEN;
  const call = async (path, token, method = 'GET', body, lease) => {
    const response = await fetch(base + path, { method,
      headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json', ...(lease ? { 'X-YAP-Lease': lease } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(240000),
    });
    const data = response.status === 204 ? null : await response.json();
    assert.ok(response.ok, `${path}: HTTP ${response.status}, code ${data?.code || 'none'}`);
    return data;
  };
  const files = unzipSync(await readFile(new URL('./fixtures/test-app.apk', import.meta.url)));
  // This repackaged ZIP is a transport boundary fixture. It is NOT
  // signed and must never be represented as a Muse-generated app.
  for (const key of Object.keys(files)) if (key.startsWith('META-INF/')) delete files[key];
  files['assets/transfer-padding.bin'] = new Uint8Array(0);
  const target = 32 * 1024 * 1024;
  const overhead = zipSync(files, { level: 0 }).length;
  files['assets/transfer-padding.bin'] = randomBytes(target - overhead);
  const apk = Buffer.from(zipSync(files, { level: 0 }));
  assert.equal(apk.length, target);
  const sha256 = createHash('sha256').update(apk).digest('hex');
  await call('/api/build', guest, 'POST', { id, prompt: '32 MiB unsigned transport boundary fixture only', responseMode: 'apk' });
  const claim = await call('/api/build/claim', worker, 'POST', { claimRequestId: randomUUID() });
  assert.equal(claim?.id, id);
  const lease = claim.lease;
  try {
    const prepared = await call(`/api/build/${id}/artifacts/prepare`, worker, 'POST', { operationId: randomUUID(), kind: 'apk', size: apk.length, sha256 }, lease);
    assert.equal(prepared.method, 'tus');
    const metadata = Object.entries({ bucketName: prepared.bucket, objectName: prepared.objectPath, contentType: 'application/vnd.android.package-archive' }).map(([key, value]) => `${key} ${Buffer.from(value).toString('base64')}`).join(',');
    const headers = { 'Tus-Resumable': '1.0.0', 'x-signature': prepared.uploadToken };
    const creation = await fetch(prepared.uploadUrl, { method: 'POST', headers: { ...headers, 'Upload-Length': String(apk.length), 'Upload-Metadata': metadata }, signal: AbortSignal.timeout(120000) });
    if (!creation.ok) {
      const detail = (await creation.text()).replaceAll(prepared.uploadToken, '[redacted]').slice(0,300);
      assert.fail(`TUS create HTTP ${creation.status}: ${detail}`);
    }
    const location = new URL(creation.headers.get('location'), prepared.uploadUrl);
    assert.equal(location.origin, new URL(prepared.uploadUrl).origin);
    const chunk = 6 * 1024 * 1024;
    for (let offset = 0; offset < apk.length;) {
      const next = Math.min(apk.length, offset + chunk);
      const patch = await fetch(location, { method: 'PATCH', headers: { ...headers, 'Content-Type': 'application/offset+octet-stream', 'Upload-Offset': String(offset) }, body: apk.subarray(offset, next), signal: AbortSignal.timeout(240000) });
      assert.ok(patch.ok, `TUS PATCH HTTP ${patch.status}`);
      assert.equal(Number(patch.headers.get('upload-offset')), next);
      offset = next;
    }
    const result = await call(`/api/build/${id}/result`, worker, 'PUT', { operationId: randomUUID(), artifactId: prepared.artifactId, verification: { note: 'Unsigned 32 MiB transport fixture, not a production APK or Muse build.' } }, lease);
    assert.equal(result.status, 'ready');
    const download = await call(`/api/build/${id}/download`, guest);
    const bytes = Buffer.from(await (await fetch(download.url, { signal: AbortSignal.timeout(240000) })).arrayBuffer());
    assert.equal(bytes.length, target);
    assert.equal(createHash('sha256').update(bytes).digest('hex'), sha256);
    console.log(JSON.stringify({ evidence: 'cloud-32mib-unsigned-transport-fixture', jobId: id, size: target, sha256, tusVerified: true, downloadVerified: true }));
  } catch (error) {
    // Leave no active worker lease behind on a failed transport test.
    await call(`/api/build/${id}/fail`, worker, 'PUT', { operationId: randomUUID(), errorCode: 'transport_test_failed' }, lease).catch(() => {});
    throw error;
  }
});
