package com.example.yap_finalprojectpapb.ui.screens

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.widget.Toast
import androidx.compose.foundation.background
import androidx.compose.foundation.horizontalScroll
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.outlined.ArrowBack
import androidx.compose.material.icons.outlined.ContentCopy
import androidx.compose.material.icons.outlined.Description
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.yap_finalprojectpapb.ui.theme.*

@Composable
fun CodeViewerScreen(
    htmlCode: String = "",
    cssCode: String = "",
    jsCode: String = "",
    onBackClick: () -> Unit = {}
) {
    val context = LocalContext.current
    var selectedFileIndex by remember { mutableIntStateOf(0) }

    val defaultHtml = if (htmlCode.isNotBlank()) htmlCode else """
        <!DOCTYPE html>
        <html lang="id">
        <head>
          <meta charset="UTF-8">
          <meta name="viewport" content="width=device-width, initial-scale=1.0">
          <title>YAP Web Studio App</title>
          <link rel="stylesheet" href="style.css">
          <script src="https://cdn.tailwindcss.com"></script>
        </head>
        <body class="bg-slate-50 text-slate-900 p-6">
          <main class="max-w-lg mx-auto bg-white rounded-2xl shadow-sm border border-slate-200 p-6">
            <h1 class="text-2xl font-bold mb-2">YAP Generated App</h1>
            <p class="text-slate-600 text-sm mb-4">Aplikasi web ini berhasil dibuat dengan bantuan AI.</p>
            <button id="btnClick" class="w-full bg-blue-600 text-white font-medium py-2.5 rounded-xl">
              Klik Saya
            </button>
          </main>
          <script src="app.js"></script>
        </body>
        </html>
    """.trimIndent()

    val defaultCss = if (cssCode.isNotBlank()) cssCode else """
        /* Custom Styles generated by YAP Studio */
        body {
          margin: 0;
          font-family: system-ui, -apple-system, sans-serif;
          -webkit-font-smoothing: antialiased;
        }

        button:active {
          transform: scale(0.98);
        }
    """.trimIndent()

    val defaultJs = if (jsCode.isNotBlank()) jsCode else """
        // Application logic generated by YAP
        document.addEventListener('DOMContentLoaded', () => {
          const btn = document.getElementById('btnClick');
          if (btn) {
            btn.addEventListener('click', () => {
              console.log('Button clicked successfully!');
            });
          }
        });
    """.trimIndent()

    val files = listOf(
        Pair("index.html", defaultHtml),
        Pair("style.css", defaultCss),
        Pair("app.js", defaultJs)
    )

    val currentCode = files[selectedFileIndex].second

    Surface(
        modifier = Modifier.fillMaxSize(),
        color = Neutral100
    ) {
        Column(modifier = Modifier.fillMaxSize()) {
            // Header Top Bar
            Surface(
                modifier = Modifier.fillMaxWidth(),
                color = NeutralWhite,
                shadowElevation = 2.dp
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 12.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    IconButton(onClick = onBackClick) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Outlined.ArrowBack,
                            contentDescription = "Kembali",
                            tint = BlueDarker
                        )
                    }

                    Column(
                        modifier = Modifier
                            .weight(1f)
                            .padding(start = 4.dp)
                    ) {
                        Text(
                            text = "Source Code Editor",
                            fontFamily = PlusJakartaSansFamily,
                            fontWeight = FontWeight.Bold,
                            fontSize = 16.sp,
                            color = BlueDarker
                        )
                        Text(
                            text = "Berkas: ${files[selectedFileIndex].first}",
                            fontFamily = PlusJakartaSansFamily,
                            fontSize = 11.sp,
                            color = Neutral500
                        )
                    }

                    // Copy Code Button
                    IconButton(
                        onClick = {
                            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                            val clip = ClipData.newPlainText("YAP Code", currentCode)
                            clipboard.setPrimaryClip(clip)
                            Toast.makeText(context, "${files[selectedFileIndex].first} disalin!", Toast.LENGTH_SHORT).show()
                        }
                    ) {
                        Icon(
                            imageVector = Icons.Outlined.ContentCopy,
                            contentDescription = "Salin Kode",
                            tint = BlueNormal
                        )
                    }
                }
            }

            // File Switcher Tabs
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 8.dp),
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                files.forEachIndexed { idx, item ->
                    FilterChip(
                        selected = selectedFileIndex == idx,
                        onClick = { selectedFileIndex = idx },
                        label = {
                            Text(
                                text = item.first,
                                fontFamily = PlusJakartaSansFamily,
                                fontSize = 12.sp,
                                fontWeight = if (selectedFileIndex == idx) FontWeight.Bold else FontWeight.Medium
                            )
                        },
                        leadingIcon = {
                            Icon(
                                imageVector = Icons.Outlined.Description,
                                contentDescription = null,
                                modifier = Modifier.size(16.dp)
                            )
                        },
                        colors = FilterChipDefaults.filterChipColors(
                            selectedContainerColor = BlueLight,
                            selectedLabelColor = BlueNormal
                        )
                    )
                }
            }

            // Monospace Code Editor Card
            Box(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 8.dp)
                    .clip(RoundedCornerShape(16.dp))
                    .background(Color(0xFF0F172A)) // Sleek dark slate editor background
            ) {
                val lines = currentCode.lines()
                Row(
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .horizontalScroll(rememberScrollState())
                        .padding(16.dp)
                ) {
                    // Line numbers column
                    Column(
                        modifier = Modifier.padding(end = 16.dp),
                        horizontalAlignment = Alignment.End
                    ) {
                        lines.indices.forEach { lineNum ->
                            Text(
                                text = "${lineNum + 1}",
                                fontFamily = FontFamily.Monospace,
                                fontSize = 12.sp,
                                color = Color(0xFF475569), // Muted line number
                                lineHeight = 18.sp
                            )
                        }
                    }

                    // Code text column
                    Column {
                        lines.forEach { line ->
                            Text(
                                text = if (line.isEmpty()) " " else line,
                                fontFamily = FontFamily.Monospace,
                                fontSize = 12.sp,
                                color = Color(0xFFF1F5F9), // Crisp off-white text
                                lineHeight = 18.sp
                            )
                        }
                    }
                }
            }

            Spacer(modifier = Modifier.height(12.dp))
        }
    }
}
